"""Universal agent-file export: AGENTS.md, MEMORY.md, and per-tool rule files.

Markdown memory files in `.agent-m3m/` remain the single source of truth.
Exported files are derived artifacts whose generated content always lives
inside a managed block, so regeneration never clobbers user content and
re-importing an export is a no-op.
"""

import re
from pathlib import Path
from typing import Any, Dict, List, Optional, Tuple

from .config import Config
from .models import MemoryScope, MemoryType, SECTION_TITLES
from .store import (
    AGENTS_EXPORT_GITIGNORE_ENTRY,
    MEMORY_EXPORT_GITIGNORE_ENTRY,
    MemoryStore,
    ensure_local_artifacts_ignored,
)
from .textutils import jaccard, meaningful_tokens

MARKER_START = "<!-- m3m:start (generated by agent-m3m; regenerate: m3m export-universal) -->"
MARKER_END = "<!-- m3m:end -->"

# Export-only clustering: variants of the same fact (paraphrases captured
# across sessions) collapse to the best-ranked one in the exported file.
# The store keeps every variant; `m3m dedup --apply` is the store cleanup.
EXPORT_CLUSTER_JACCARD = 0.60

# Section render order mirrors SECTION_TITLES definition order.
_SECTION_ORDER = list(SECTION_TITLES.items())

MEMORY_INDEX_MAX_LINES = 200
MEMORY_INDEX_MAX_CHARS = 25_000

DEFAULT_TARGETS = ("agents", "memory")

TARGET_GITIGNORE_ENTRIES = {
    "agents": AGENTS_EXPORT_GITIGNORE_ENTRY,
    "memory": MEMORY_EXPORT_GITIGNORE_ENTRY,
}

TARGETS: Dict[str, Dict[str, Any]] = {
    "agents": {"path": "AGENTS.md", "kind": "instructions", "owned": False},
    "memory": {"path": "MEMORY.md", "kind": "index", "owned": False},
    "claude": {"path": "CLAUDE.md", "kind": "instructions", "owned": False},
    "gemini": {"path": "GEMINI.md", "kind": "instructions", "owned": False},
    "cursor": {
        "path": ".cursor/rules/m3m-memory.mdc",
        "kind": "instructions",
        # m3m-owned filename: the whole file (frontmatter included) is ours.
        "owned": True,
        "frontmatter": "---\ndescription: Persistent memory exported by agent-m3m\nglobs:\nalwaysApply: true\n---\n",
    },
    "windsurf": {
        "path": ".windsurf/rules/m3m-memory.md",
        "kind": "instructions",
        "owned": True,
        "frontmatter": "---\ntrigger: always_on\ndescription: Persistent memory exported by agent-m3m\n---\n",
    },
    "copilot": {"path": ".github/copilot-instructions.md", "kind": "instructions", "owned": False},
    "cline": {"path": ".clinerules/m3m-memory.md", "kind": "instructions", "owned": True},
    "kiro": {
        "path": ".kiro/steering/m3m-memory.md",
        "kind": "instructions",
        "owned": True,
        "frontmatter": "---\ninclusion: always\n---\n",
    },
}


def select_memories(
    config: Config,
    store: MemoryStore,
    limit: Optional[int] = None,
    include_global: bool = False,
) -> List:
    """Rank THIS project's memories for export, bounded by the line budget.

    Exports are per-repository artifacts: only memories that belong to the
    project where the command runs are included. Global memories leak
    unrelated project knowledge into other repos, so they are opt-in via
    ``include_global`` (and even then only preferences/conventions travel).
    """
    max_items = limit or config.export_universal_max_lines
    ranked: List = []
    scopes = [MemoryScope.PROJECT]
    if include_global:
        scopes.append(MemoryScope.GLOBAL)
    for scope in scopes:
        items = [
            item for item in store.list_items(scope=scope, status="active")
            if not item.is_expired()
        ]
        if scope == MemoryScope.PROJECT:
            items = [
                item for item in items
                if not item.project_id or not config.project_id or item.project_id == config.project_id
            ]
        else:
            items = [
                item for item in items
                if item.type in {MemoryType.PREFERENCE, MemoryType.CONVENTION}
            ]
        items.sort(key=lambda item: (
            bool(item.pinned),
            int(item.use_count or 0),
            float(item.confidence or 0.0),
            len(item.content),
            item.updated or "",
        ), reverse=True)
        ranked.extend(items)
    # De-duplicate exact repeats across scopes while keeping the ranking.
    seen = set()
    selected: List = []
    for item in ranked:
        key = " ".join(item.content.lower().split())
        if key in seen:
            continue
        seen.add(key)
        selected.append(item)
        if len(selected) >= max_items:
            break
    return selected


def render_instructions(items: List, max_lines: int) -> Tuple[str, int]:
    """Render budgeted instruction sections; returns (body, memory_count).

    `max_lines` bounds the rendered line count (headers and blanks included)
    so exported files respect the community guidance of staying short.
    """
    buckets: Dict[str, List] = {}
    for item in items:
        item_type = item.type if isinstance(item.type, MemoryType) else MemoryType.PREFERENCE
        title = SECTION_TITLES.get(item_type, "Other")
        buckets.setdefault(title, []).append(item.content.strip())

    lines: List[str] = ["# Project Memory", ""]
    used_lines = 2
    count = 0
    for _mtype, title in _SECTION_ORDER:
        entries = buckets.get(title)
        if not entries:
            continue
        remaining = max_lines - used_lines - 2  # section header + blank
        if remaining <= 0:
            continue
        entries = entries[:remaining]
        lines.append(f"## {title}")
        lines.extend(f"- {entry}" for entry in entries)
        lines.append("")
        used_lines += 2 + len(entries)
        count += len(entries)
    return "\n".join(lines).rstrip() + "\n", count


def render_memory_index(items: List) -> Tuple[str, int]:
    """Render a MEMORY.md-style index: one line per memory (≤200 lines/25KB)."""
    lines: List[str] = [
        "# Memory Index",
        "",
        "<!-- One line per memory. Bodies live in .agent-m3m/<scope>/<type>/<id>.md -->",
        "",
    ]
    count = 0
    for item in items[: MEMORY_INDEX_MAX_LINES - len(lines) - 2]:
        scope = item.scope.value if isinstance(item.scope, MemoryScope) else str(item.scope)
        item_type = item.type.value if isinstance(item.type, MemoryType) else str(item.type)
        content = " ".join(item.content.split())
        pinned = " [pinned]" if item.pinned else ""
        lines.append(f"- [{scope}/{item_type}]{pinned} {content} (id={item.id})")
        count += 1
    body = "\n".join(lines).rstrip() + "\n"
    if len(body) > MEMORY_INDEX_MAX_CHARS:
        body = body[:MEMORY_INDEX_MAX_CHARS].rstrip() + "\n"
    return body, count


def build_managed_block(body: str) -> str:
    return f"{MARKER_START}\n{body.rstrip()}\n{MARKER_END}\n"


def merge_managed_block(existing_content: str, block: str) -> str:
    """Replace the managed block, or append it without touching user content."""
    if MARKER_START in existing_content and MARKER_END in existing_content:
        pattern = re.compile(
            re.escape(MARKER_START) + r"\n.*?\n" + re.escape(MARKER_END) + r"\n?",
            re.DOTALL,
        )
        if pattern.search(existing_content):
            return pattern.sub(block, existing_content, count=1)
    if not existing_content.strip():
        return block
    if existing_content.endswith("\n\n"):
        return existing_content + block
    if existing_content.endswith("\n"):
        return existing_content + "\n" + block
    return existing_content + "\n\n" + block


def cluster_export_items(items: List) -> List:
    """Collapse near-duplicate variants for the exported file only.

    Agents should read one instruction, not five paraphrases of it. The
    first (best-ranked, usually most complete) variant wins. Cross-language
    paraphrases survive lexical clustering by design — clean the store with
    `m3m dedup --apply` for that.
    """
    kept: List = []
    kept_tokens: List[set] = []
    for item in items:
        tokens = meaningful_tokens(item.content)
        if tokens and any(jaccard(tokens, prev) >= EXPORT_CLUSTER_JACCARD for prev in kept_tokens):
            continue
        kept.append(item)
        kept_tokens.append(tokens)
    return kept


def run_universal_export(
    config: Config,
    store: MemoryStore,
    targets: List[str],
    limit: Optional[int] = None,
    dry_run: bool = False,
    include_global: bool = False,
) -> List[Dict[str, Any]]:
    """Write (or preview) the selected universal export targets.

    Per-project by default: only memories belonging to the project where the
    command runs are exported. Returns one report row per target:
    {target, path, memories, lines, action}.
    """
    project_root = config.project_root
    root = project_root or Path.cwd()
    items = cluster_export_items(
        select_memories(config, store, limit=limit, include_global=include_global)
    )
    report: List[Dict[str, Any]] = []

    for target in targets:
        spec = TARGETS[target]
        target_path = root / spec["path"]
        if spec["kind"] == "index":
            body, count = render_memory_index(items)
        else:
            body, count = render_instructions(items, config.export_universal_max_lines)
        block = build_managed_block(body)
        lines = block.count("\n") + 1

        action = "create"
        if target_path.exists():
            existing = target_path.read_text(encoding="utf-8")
            if spec["owned"]:
                action = "replace"
                # m3m-owned rule files are fully regenerated, frontmatter included.
                content = spec.get("frontmatter", "") + block
            else:
                action = "update" if MARKER_START in existing else "append"
                content = merge_managed_block(existing, block)
        else:
            content = spec.get("frontmatter", "") + block

        if not dry_run:
            target_path.parent.mkdir(parents=True, exist_ok=True)
            target_path.write_text(content, encoding="utf-8")
            gitignore_entry = TARGET_GITIGNORE_ENTRIES.get(target)
            if gitignore_entry and project_root is not None:
                ensure_local_artifacts_ignored(project_root, (gitignore_entry,))

        report.append({
            "target": target,
            "path": str(target_path),
            "memories": count,
            "lines": lines,
            "action": action,
        })
    return report
